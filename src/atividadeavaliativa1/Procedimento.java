public class Procedimento {
    private String nome;
    private int duracaoEstimada;
    private double valor;
    private int complexidade;

    /**
     * @return the nome
     */
    public String getNome() {
        return nome;
    }

    /**
     * @param nome the nome to set
     */
    public void setNome(String nome) {
        this.nome = nome;
    }

    /**
     * @return the duracaoEstimada
     */
    public int getDuracaoEstimada() {
        return duracaoEstimada;
    }

    /**
     * @param duracaoEstimada the duracaoEstimada to set
     */
    public void setDuracaoEstimada(int duracaoEstimada) {
        this.duracaoEstimada = duracaoEstimada;
    }

    /**
     * @return the valor
     */
    public double getValor() {
        return valor;
    }

    /**
     * @param valor the valor to set
     */
    public void setValor(double valor) {
        this.valor = valor;
    }

    /**
     * @return the complexidade
     */
    public int getComplexidade() {
        return complexidade;
    }

    /**
     * @param complexidade the complexidade to set
     */
    public void setComplexidade(int complexidade) {
        this.complexidade = complexidade;
    }
}
